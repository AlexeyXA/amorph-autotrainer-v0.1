def create_demo_csv(output_path: str | Path, examples_per_class: int = 50) -> Path:
    """Create deterministic synthetic data for a smoke test, not benchmarking."""
    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["text", "label"])
        writer.writeheader()
        for label, templates in TEMPLATES.items():
            for i in range(examples_per_class):
                template = templates[i % len(templates)]
                # Variation avoids exact duplicates but the signal remains intentionally simple.
                text = f"{template}. Демонстрационный выпуск {i + 1}, редакция {i % 7 + 1}."
                writer.writerow({"text": text, "label": label})
    return output
